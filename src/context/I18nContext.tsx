const translations: Record<LangCode, Dictionary> = Object.fromEntries(
  languages.map((l) => {
    const code = l.code;
    return [
      code,
      {
        ...baseTranslations[code],
        ...localizedCoreOverrides[code],
        ...localizedEcosystemOverrides[code],
        ...localizedMissingOverrides[code],
      },
    ];
  }),
) as Record<LangCode, Dictionary>;

// Development audit: warn when specific keys are still identical to English
if (process.env.NODE_ENV !== 'production') {
  const auditKeys: TranslationKey[] = [
    'capability.multi_task',
    'capability.natural_language',
    'capability.workflow_automation',
    'capability.self_improving_ai',
    'founder.statement',
    'contact.note',
    'contact.name',
    'contact.placeholder.name',
    'contact.purpose',
    'contact.placeholder.purpose',
  ];

  const auditResult: Record<string, string[]> = {};
  languages.forEach((l) => {
    const code = l.code as LangCode;
    if (code === 'en') return;
    const missing = auditKeys.filter((k) => {
      try {
        return translations[code][k] === en[k];
      } catch {
        return true;
      }
    });
    if (missing.length) {
      auditResult[code] = missing;
      // eslint-disable-next-line no-console
      console.warn('[i18n-audit] language', code, 'has untranslated keys:', missing);
    }
  });
  try {
    // expose results for automated checks in dev
    // @ts-ignore
    if (typeof window !== 'undefined') window.__i18nAudit = auditResult;
  } catch {}
}

interface I18nContextType {
  lang: LangCode;
  setLang: (lang: LangCode) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextType | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>(() => {
    try {
      if (typeof window !== 'undefined') {
        const saved = localStorage.getItem('zf4a-lang') as LangCode | null;
        if (saved && languages.find(l => l.code === saved)) return saved;
        const browserLang = (navigator.language || 'en').split('-')[0] as LangCode;
        if (languages.find(l => l.code === browserLang)) return browserLang;
      }
    } catch {
      // ignore storage read errors
    }
    return 'en';
  });

  const setLang = useCallback((newLang: LangCode) => {
    setLangState(newLang);
    try {
      localStorage.setItem('zf4a-lang', newLang);
    } catch {
      // ignore storage write errors
    }
  }, []);

  const t = useCallback((key: string) => {
    return translations[lang][key as TranslationKey] || en[key as TranslationKey] || key;
  }, [lang]);

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}
